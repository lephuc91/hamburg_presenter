		};
	}

	public static IHotKey ToEntity(this HotKey protoHotkey, IEntityFactory entityFactory)
	{
		IHotKey hotKey = entityFactory.Create<IHotKey>();
		hotKey.Code.Set(protoHotkey.Code.ToEntity());
		return hotKey;
